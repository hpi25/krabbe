export type MapKey = keyof typeof colorMaps

const lerp = (a: number, b: number, t: number) => a + (b - a) * t

const lerpColor = (a: RGBA, b: RGBA, t: number): RGBA =>
  a.map((c, i) => Math.round(lerp(c, b[i], t))) as RGBA

const unpackColor = (packed: number): RGBA => {
  const hex = packed.toString(16).padStart(8, '0')
  return Array.from({ length: 4 }, (_, i) => Number(`0x${hex.slice(2 * i, 2 * (i + 1))}`)) as RGBA
}

/** Interpolate a colour map into a palette of `steps` RGBA colours */
export const createPalette = (map: MapKey | ColorMap, steps: number): RGBA[] => {
  const stops = (typeof map === 'string' ? colorMaps[map] as ColorMap : map)
    .map(([position, color]) => ({
      index: Math.round(position * (steps - 1)),
      color: typeof color === 'number' ? unpackColor(color) : color,
    }))
    // Where several stops land on the same index, keep only one of them
    .filter(({ index }, i, all) => {
      if (index === steps - 1 && steps > 1) {
        return all.filter((s, j) => s.index === index && j > i).length < 1
      }
      if (index === 0) return all.findIndex(s => s.index === index) === i
      const sameIndex = all.filter(s => s.index === index)
      return i === all.indexOf(sameIndex[Math.floor(sameIndex.length / 2)])
    })

  return stops.flatMap((stop, i) => {
    if (i === stops.length - 1) return [stop.color]
    const length = stops[i + 1].index - stop.index
    return Array.from({ length }, (_, j) => lerpColor(stop.color, stops[i + 1].color, j / length))
  })
}
